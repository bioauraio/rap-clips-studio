"""Генерация сюжета и раскадровки через host-шлюз Claude (та же подписка,
что у контент-конвейера BIOAURA — agent_gateway.py на хосте, 172.18.0.1:8765).
Личный проект: никаких брендовых правил/продуктов, только рэп-клип."""
from __future__ import annotations

import json
import os
import re

import httpx

GATEWAY_URL = os.environ.get("AGENT_GATEWAY_URL", "http://172.18.0.1:8765") + "/complete"
TIMEOUT = httpx.Timeout(280.0, connect=15.0)


class ClaudeError(RuntimeError):
    pass


def _extract_json(text: str) -> dict:
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\n?", "", text)
        text = re.sub(r"```$", "", text).strip()
    m = re.search(r"\{.*\}", text, re.DOTALL)
    if not m:
        raise ClaudeError(f"в ответе нет JSON: {text[:300]}")
    return json.loads(m.group(0))


async def _ask(prompt: str, system: str) -> dict:
    async with httpx.AsyncClient(timeout=TIMEOUT) as client:
        r = await client.post(GATEWAY_URL, json={
            "prompt": prompt,
            "system": system,
            "subscription_provider": "claude",
            "cwd": "rapclips",
            "timeout": 260,
        })
    if r.status_code != 200:
        raise ClaudeError(f"шлюз ответил {r.status_code}: {r.text[:300]}")
    data = r.json()
    text = data.get("text", "")
    if not text:
        raise ClaudeError(f"пустой ответ шлюза: {data}")
    return _extract_json(text)


STORY_SYSTEM = """Ты — режиссёр и сценарист музыкальных видеоклипов, помогаешь сложить
единый сюжет из отдельных рэп-треков одного альбома/проекта.

Тебе дают: (опционально) уже существующее описание героя, и список треков по порядку —
для каждого номер, название, текст песни (лирика), комментарий автора (контекст,
что он имел в виду) и желаемый визуальный стиль ролика для этого трека
(например "3D мультяшный", "аниме", "реализм" — у каждого трека свой стиль,
это нормально и намеренно).

Твоя задача:
1. Если character_bible пуст — придумай ГЛАВНОГО ГЕРОЯ: кто он, как выглядит
   (внешность, одежда, характерные детали, которые легко узнать в ЛЮБОМ визуальном
   стиле — 3D, аниме, реализм), какой у него характер и путь. Если character_bible
   уже задан — сохрани его суть, можешь уточнить/расширить, но не переписывай личность
   героя с нуля.
2. Сложи ОДИН сквозной сюжет через все треки: что происходит с героем от трека к
   треку, как эмоция/тема каждого трека логически продолжает предыдущую и ведёт к
   следующей. Треки уже даны в фиксированном порядке — не меняй его, просто найди
   связку. Если где-то стыковка слабая — предложи, как её усилить смыслом (в поле
   track_notes), но НЕ выдумывай текст песен.
3. Для каждого трека дай короткую режиссёрскую заметку: что в сюжете происходит
   именно в этом треке, каким это трек показывает героя, чем предыдущий кадр
   переходит в следующий.

У части треков (или у всех) текста может НЕ БЫТЬ — это инструментал, чистый бит.
Такой трек — полноправная глава сюжета: его смысл бери из комментария автора и
общей дуги истории, а в track_notes для него опиши визуальную драматургию словами
(что происходит с героем под бит). Отсутствие лирики — не ошибка и не повод
пропустить трек.

Выведи СТРОГО один JSON без markdown-обёртки:
{
  "character_bible": "<полное описание героя: внешность, характер, атрибуты — по-русски>",
  "story": "<связный сюжет всего клипа целиком, 200-500 слов, по-русски>",
  "track_notes": [{"position": 1, "note": "<роль этого трека в сюжете, по-русски>"}]
}"""


def _characters_block(characters: list[dict]) -> str:
    """Роспись персонажей альбома для промптов: имя + характер/внешность."""
    if not characters:
        return ""
    lines = ["ПЕРСОНАЖИ АЛЬБОМА (заведены владельцем; их имена используй ДОСЛОВНО,"
             " их внешность из описания не переизобретай — только пересказывай"
             " в стилистике конкретного трека):"]
    for c in characters:
        mark = " (ГЛАВНЫЙ ГЕРОЙ)" if c.get("is_main") else ""
        photos = f" [есть {c['photos']} фото-модельки лица]" if c.get("photos") else ""
        lines.append(f"- {c['name']}{mark}{photos}: {c['description']}")
        # Фирменные вещи персонажа: называй их в кадрах ДОСЛОВНО по имени —
        # по этому имени сервер подставляет фото вещи референсом генерации.
        attrs = c.get("attributes") or []
        if attrs:
            attr_line = "; ".join(
                f"{a['name']} — {a['description']}" if a.get("description") else a["name"]
                for a in attrs
            )
            lines.append(
                f"  Фирменные вещи {c['name']} (упоминай их имена дословно,"
                f" вписывай в кадры, где они уместны): {attr_line}"
            )
    return "\n".join(lines)


async def generate_story(character_bible: str, tracks: list[dict], characters: list[dict] | None = None) -> dict:
    lines = []
    for t in tracks:
        # Инструментал без слов — валидная глава: сюжет для него складывается
        # из комментария автора, а не из несуществующей лирики.
        lyrics_line = (
            t["lyrics"] if (t["lyrics"] or "").strip()
            else "(без слов — чистый бит; смысл главы бери из комментария автора)"
        )
        lines.append(
            f"### Трек {t['position']}: {t['title']}\n"
            f"Стиль ролика: {t['style'] or '(не задан)'}\n"
            f"Комментарий автора: {t['comment'] or '(нет)'}\n"
            f"Профиль звука (замер реальной дорожки): {t.get('audio_profile') or '(нет)'}\n"
            f"Текст песни:\n{lyrics_line}\n"
        )
    chars = _characters_block(characters or [])
    prompt = (
        (chars + "\n\n" if chars else "")
        + f"character_bible (может быть пустым): {character_bible or '(пусто — придумай героя)'}\n\n"
        + "\n".join(lines)
    )
    return await _ask(prompt, STORY_SYSTEM)


SCENES_SYSTEM = """
ДИНАМИКА ОБЯЗАТЕЛЬНА: первый и последний кадры каждой сцены — РАЗНЫЕ фазы движения (замах→удар, разгон→прыжок, начало→пик действия), позы в действии, никакой статики и одинаковых поз; меняй ракурсы и крупность между сценами.
Ты — опытный кинорежиссёр и режиссёр монтажа, который строит
раскадровку музыкального видеоклипа (генеративное видео: картинка кадра → анимация
кадра, Grok image-to-video). Твоя цель — не иллюстрация текста, а НАСТОЯЩЕЕ КИНО:
монтажный ритм, крупность планов, движение камеры и свет должны работать на историю
и на энергию трека так же, как в хорошем клипе или короткометражке.

Тебе дают: сквозной сюжет всего клипа, библию героя, режиссёрскую заметку конкретно
для этого трека, текст песни, комментарий автора, визуальный стиль ЭТОГО трека и его
длительность в секундах.

ТРЕК БЕЗ ТЕКСТА (чистый бит, инструментал) — нормальный, полноценный случай.
Тогда идея ролика — это комментарий автора: он заменяет лирику целиком. Строй
драматургию сам (завязка → развитие → кульминация → финал) из комментария,
сквозного сюжета и персонажей альбома, а монтажный ритм — из длительности и
характера бита (энергичный бит — короткие кадры, медитативный — длинные).
lyric_line у всех кадров оставляй пустым; отсутствие текста НЕ повод делать
меньше кадров или беднее историю.

КОЛИЧЕСТВО КАДРОВ — НЕ ФИКСИРОВАНО. Раскадровка обслуживает историю и структуру
трека (интро/куплет/хук/бридж/аутро), а не наоборот. На энергичном хуке кадры короче
и чаще (быстрый монтаж, 2-4 сек), на медленном куплете или лиричном моменте —
длиннее (6-10 сек, кадру дают подышать). Общее число кадров может доходить до
нескольких десятков на длинный трек — не экономь на них, если того требует история.
СУММА duration_sec всех кадров = длительность трека (округляй разумно, остаток не
больше пары секунд).

КРУПНОСТЬ ПЛАНА — ОБЯЗАТЕЛЬНОЕ ПОЛЕ "shot_size", используй монтажную грамматику:
  - "extreme close-up" — деталь (глаза, руки, предмет) — для акцента и напряжения;
  - "close-up" — лицо/эмоция героя — для эмоциональных пиков, ключевых строк;
  - "medium" — по пояс — для диалога состояний, действия;
  - "wide" — герой в среде целиком — для контекста, одиночества, масштаба;
  - "establishing" — общий план локации, часто БЕЗ героя — открывает новую сцену/главу.
ПРАВИЛО МОНТАЖА: не ставь два одинаковых по крупности плана подряд — чередуй крупные
с дальними (close-up → wide → medium → close-up …), это держит зрительский ритм.
Каждую смену локации или главы истории открывай establishing-планом. Кульминационные
строки текста (хук, самая сильная метафора) — почти всегда close-up или extreme
close-up: там, где нужна максимальная эмоция, крупность растёт.

ДВИЖЕНИЕ КАМЕРЫ — разнообразь среди: static, slow push-in, slow pull-out, slow pan,
handheld subtle shake, low-angle tilt up (герой выглядит сильнее), high-angle tilt
down (герой выглядит уязвимее). Выбор угла и движения — тоже режиссёрское решение,
привязанное к тому, что герой чувствует в этот момент.

СВЯЗНОСТЬ ИСТОРИИ:
- Герой (или явное продолжение его пути) должен быть узнаваем в кадрах, где он
  присутствует — используй его описание из character_bible дословно в каждом
  image_prompt, где он в кадре.
- Не иллюстрируй текст построчно — веди историю героя, синхронизируясь с настроением
  и ключевыми образами лирики; вставляй "немые" кадры-связки (без lyric_line) там,
  где нужен визуальный вдох или переход между локациями/главами.
- Стиль ролика ЭТОГО трека — {STYLE}. Все image_prompt обязаны начинаться с явного
  указания этого стиля (например "3D Pixar-style animation, vertical 9:16, ultra HD,"
  или "Anime style, vertical 9:16, cinematic," или "Photorealistic cinematic still,
  vertical 9:16," — подбери формулировку под заданный стиль) и явно называть
  выбранную крупность плана и ракурс.

ПОЛЯ КАЖДОГО КАДРА:
- "duration_sec": целое число 2-10, по логике темпа/структуры (см. выше).
- "shot_size": одно из extreme close-up / close-up / medium / wide / establishing.
- "camera_move": короткая фраза по-английски (напр. "slow push-in", "static").
- "lyric_line": строка/фрагмент лирики, которому соответствует кадр (можно пусто —
  для кадров-связок и establishing-планов это нормально).
- "shot_note": по-русски, 1-2 фразы — что в кадре, что происходит, почему именно
  такая крупность/движение здесь.
- "characters": массив ИМЁН персонажей, которые находятся в этом кадре (точно
  как в списке персонажей альбома; пустой массив — если кадр без персонажей).
  В image_prompt и image_prompt_last каждого кадра с персонажем ОБЯЗАТЕЛЬНО
  входит полное описание внешности каждого присутствующего персонажа (из его
  карточки), пересказанное в стилистике трека; имя персонажа тоже упоминается.
- "image_prompt": промпт ПЕРВОГО кадра сцены (её начало), на английском. Начинай со
  стиля, затем крупность плана и ракурс, затем герой (если в кадре — его полное
  описание из character_bible), окружение, композиция, свет, настроение.
- "image_prompt_last": промпт ПОСЛЕДНЕГО кадра этой же сцены (её конец), на
  английском. Это ТА ЖЕ сцена в конце своего движения: та же локация, тот же
  герой, тот же стиль и свет — меняется только то, что успело произойти за
  duration_sec (поза, положение в кадре, крупность из-за наезда камеры, фаза
  света). Не меняй персонажа, одежду, время суток и место — иначе видео между
  кадрами «прыгнет». Описывай так же полно, как первый кадр (модель видит их
  независимо).
- "motion_prompt": промпт для АНИМАЦИИ этого кадра (Grok image-to-video), на
  английском. КРИТИЧНО: модель анимирует кадр ИЗОЛИРОВАННО, не зная соседних кадров.
  Не ссылайся на другие кадры ("same as before", "continues", "again"). Внешность
  героя и среду повторно не описывай — они уже есть в картинке, опиши только ДВИЖЕНИЕ
  (героя, камеры, света) за длительность кадра, включая camera_move: исходное
  состояние → движение → финальное состояние. Движение простое и физически
  правдоподобное. Без морфинга и резких трансформаций.

Выведи СТРОГО один JSON без markdown-обёртки:
{"scenes":[{"duration_sec":6,"shot_size":"close-up","camera_move":"slow push-in","lyric_line":"...","shot_note":"...","characters":["Имя"],"image_prompt":"...","image_prompt_last":"...","motion_prompt":"..."}]}"""


STORYBOARD_SHEET_SYSTEM = """Ты пишешь промпт для генерации ЕДИНОГО ЛИСТА РАСКАДРОВКИ
(storyboard contact sheet) музыкального клипа — одной картинки, на которой сеткой
показаны все кадры трека подряд.

Смысл листа: увидеть клип ЦЕЛИКОМ до покадровой отрисовки — единый ли герой,
держится ли стиль, не рассыпается ли монтаж. Этот же лист потом идёт художнику
(модели) контекстом при отрисовке отдельных кадров.

Тебе дают: стиль ролика, библию героя и список кадров (номер, крупность, что
происходит). Составь ОДИН промпт на английском, который:
- явно просит storyboard contact sheet / grid layout с пронумерованными панелями
  (по числу кадров, аккуратной сеткой, каждая панель вертикальная 9:16);
- задаёт единый визуальный стиль всех панелей (стиль трека) и единого героя
  (краткая, но узнаваемая выжимка из библии: волосы, глаза, одежда, метка);
- перечисляет содержимое панелей по порядку одной-двумя фразами каждая, с
  указанием крупности плана;
- запрещает текст и подписи внутри панелей, кроме номеров.

Выведи СТРОГО один JSON без markdown-обёртки:
{"prompt":"<готовый английский промпт листа раскадровки>"}"""


async def generate_storyboard_sheet_prompt(
    *, style: str, character_bible: str, scenes: list[dict],
    characters: list[dict] | None = None,
) -> dict:
    lines = [
        f"{s['position']}. [{s.get('shot_size') or 'plan'}] {s.get('shot_note') or ''}"
        for s in scenes
    ]
    chars = _characters_block(characters or [])
    prompt = (
        (chars + "\n\n" if chars else "")
        + f"Стиль ролика: {style or '(на твой выбор)'}\n\n"
        f"Библия героя:\n{character_bible}\n\n"
        "ВАЖНО: на каждом кадре листа, где есть персонаж, он обязан выглядеть "
        "СТРОГО по своему описанию выше (лицо, причёска, одежда, татуировки, "
        "атрибуты) — в выбранной стилистике, но узнаваемо. Не выдумывай других героев.\n\n"
        f"Кадры ({len(scenes)} шт.):\n" + "\n".join(lines)
    )
    return await _ask(prompt, STORYBOARD_SHEET_SYSTEM)


async def generate_scenes(
    *, story: str, character_bible: str, track_note: str, title: str,
    lyrics: str, comment: str, style: str, duration_sec: int,
    characters: list[dict] | None = None, audio_profile: str = "",
) -> dict:
    system = SCENES_SYSTEM.replace("{STYLE}", style or "стиль на твой выбор, подходящий треку")
    chars = _characters_block(characters or [])
    # Ветка «чистый бит»: без лирики идею несут комментарий автора и персонажи —
    # говорим это модели прямо, чтобы она не искала несуществующий текст.
    if lyrics.strip():
        lyrics_block = f"Текст песни:\n{lyrics}"
    else:
        lyrics_block = (
            "Текст песни: НЕТ — это трек без слов, чистый бит. Идея ролика — "
            "комментарий автора выше; строй историю из него, сюжета и персонажей, "
            "ритм монтажа — под бит и длительность аудио."
        )
    story_block = (
        "РЕЖИМ «БЕЗ СЮЖЕТА»: связная история НЕ нужна. Каждый кадр — независимый "
        "самодостаточный панч-образ по идеям из комментария автора (как нарезка "
        "рандомных вирусных клипов). Никакой сквозной драматургии, только максимум "
        "выразительности в каждом отдельном кадре."
        if not (story or "").strip() else f"Сюжет всего клипа:\n{story}"
    )
    prompt = (
        (chars + "\n\n" if chars else "")
        + story_block + "\n\n"
        f"Библия героя:\n{character_bible}\n\n"
        f"Роль этого трека в сюжете:\n{track_note or '(нет заметки — определи сам по тексту песни и комментарию)'}\n\n"
        f"Трек: {title}\nСтиль ролика: {style or '(на твой выбор)'}\n"
        f"Длительность аудио: {duration_sec} секунд\n"
        f"Профиль звука (замер реальной дорожки — сажай ритм сцен на эту динамику: "
        f"тихие сегменты = спокойные планы, врывы = экшен и резкие склейки): "
        f"{audio_profile or '(нет замера)'}\n"
        f"Комментарий автора: {comment or '(нет)'}\n\n"
        + lyrics_block
    )
    return await _ask(prompt, system)


