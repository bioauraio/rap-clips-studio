async def generate_ugc_scenes(*, persona: str, character_bible: str,
                              location_bible: str, format_beats: str,
                              format_note: str, brief: str, style: str,
                              slots: int, duration_sec: int, rules: str,
                              lang: str = "ru") -> dict:
    system = (UGC_SCENES_SYSTEM
              .replace("{RULES}", rules)
              .replace("{SLOTS}", str(slots)))
    prompt = (
        f"Персона блогера:\n{persona or '(не задана — держи нейтральный дружелюбный тон)'}\n\n"
        f"ДОСЛОВНАЯ формула внешности (повторяй в каждом промпте слово в слово):\n"
        f"{character_bible or '(не задана — придумай и повторяй неизменно)'}\n\n"
        f"ДОСЛОВНАЯ формула локации (повторяй в каждом промпте слово в слово):\n"
        f"{location_bible or '(не задана — придумай и повторяй неизменно)'}\n\n"
        f"Визуальный стиль: {style or '(любительская смартфонная съёмка)'}\n"
        f"Язык реплик: {'русский' if lang == 'ru' else 'английский'}\n"
        f"Длительность ролика: около {duration_sec} секунд\n"
        f"Режиссёрская установка формата: {format_note}\n\n"
        f"Каркас формата (доли хронометража):\n{format_beats}\n\n"
        f"Бриф ролика:\n{brief or '(пусто — сделай ролик по каркасу и персоне)'}"
    )
    return await _ask(prompt, system)
